"""Markdown and JSON contract reports (the pull-request comment body)."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from . import __version__
from .diff import Change, summary

ICON = {"breaking": "🔴", "breaking_no_known_consumers": "🟠", "compatible": "🟢"}
TITLE = {"breaking": "Breaking for known consumers", "breaking_no_known_consumers": "Breaking, but no known consumer uses it",
         "compatible": "Compatible"}


def _c(s: str) -> str:
    return f"`{s.replace('`', chr(39))}`" if s else "–"


def build(base_label: str, head_label: str, title: str, changes: list[Change], impact: dict) -> dict[str, Any]:
    return {
        "tool": f"k11-api-contract-qa-mcp {__version__}",
        "generatedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "api": title, "base": base_label, "head": head_label,
        "summary": summary(changes), "impact": impact,
        "changes": [c.to_dict() for c in changes],
    }


def to_markdown(r: dict[str, Any]) -> str:
    imp, s = r["impact"], r["summary"]
    v = imp["verdict"]
    L = [f"## API contract check: {ICON[v]} {TITLE[v]}", ""]
    L.append(f"**{r['api']}**: {_c(r['base'])} → {_c(r['head'])}. {s['total']} change(s), **{s['breaking']} breaking**"
             + (f" (worst: {s['worst']})" if s["worst"] else "") + f"; {imp['consumers_known']} known consumer(s), "
             f"**{len(imp['consumers_broken'])} affected**.")
    L.append("")
    if imp["needs_human"]:
        L += [f"> **Needs a person before merge:** {imp['needs_human_reason']}.", ""]
    if imp["consumers_broken"]:
        L += ["### Affected consumers", "", "| Consumer | Owner | Criticality | Breaking change | Why it affects them |",
              "|---|---|---|---|---|"]
        for b in imp["consumers_broken"]:
            for i, ch in enumerate(b["changes"]):
                who = f"**{b['consumer']}**" + (f" ({b['repo']})" if b["repo"] else "") if i == 0 else ""
                L.append(f"| {who} | {b['owner'] if i == 0 else ''} | {b['criticality'] if i == 0 else ''} | "
                         f"{_c(ch['endpoint'])}: {ch['description']} | {ch['why']} |")
        L.append("")
    if imp["breaking_without_known_consumers"]:
        L += ["### Breaking, no known consumer", "",
              "Not used by any consumer in `.qa-mcp/consumers.yaml`. Safe only if that list is complete.", ""]
        L += [f"- {_c(ch['endpoint'])}: {ch['description']} ({ch['severity']}, rule `{ch['rule']}`)"
              for ch in imp["breaking_without_known_consumers"]]
        L.append("")
    compat = [c for c in r["changes"] if not c["breaking"]]
    if compat:
        L += ["<details><summary>Compatible changes (" + str(len(compat)) + ")</summary>", ""]
        L += [f"- {_c(c['endpoint'])}: {c['description']}" for c in compat]
        L += ["", "</details>", ""]
    L += [f"<sub>Generated by {r['tool']} at {r['generatedAt']}. Deterministic rules, no LLM. "
          "Full evidence: contract-report.json.</sub>", ""]
    return "\n".join(L)


def write(r: dict[str, Any], out_dir: Path) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    j, m = out_dir / "contract-report.json", out_dir / "contract-report.md"
    j.write_text(json.dumps(r, indent=2, ensure_ascii=False) + "\n", "utf8")
    m.write_text(to_markdown(r), "utf8")
    return m, j
